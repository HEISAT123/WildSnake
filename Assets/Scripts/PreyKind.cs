namespace WildSnake
{
    /// <summary>Виды добычи. Числовые значения используются как индексы массивов.</summary>
    public enum PreyKind
    {
        /// <summary>Жук: мелочь, не убегает, ловится касанием.</summary>
        Beetle = 0,
        /// <summary>Мышь: убегает рывками, ловится броском.</summary>
        Mouse = 1,
        /// <summary>Лягушка: упрыгивает, ловится броском.</summary>
        Frog = 2,
        /// <summary>Птица: сытная и пугливая, улетает; ночью спит. Лучше всего ловится из засады.</summary>
        Bird = 3,
        /// <summary>Кролик: крупная добыча — схватить броском и задушить, обвив (F).</summary>
        Rabbit = 4,
        /// <summary>Ёж: заметив змею, сворачивается в колючий шар — укус ранит саму змею. Брать, пока не заметил.</summary>
        Hedgehog = 5,
        /// <summary>Рыба: живёт в реке и озере, держится под самой поверхностью и иногда выпрыгивает. Ловится броском.</summary>
        Fish = 6
    }
}
